/**
 * Enum for date/value chart rendering types.
 * Defines the visual representation style: Bar, Line, Dot, or Pie, a series drawn as Pie being a
 * slice of a pie per period shared with the chart's other Pie series.
 */
Ren.SeriesChartTypeEnum = Ren.DefineEnum({
    Bar: 0,
    Line: 1,
    Dot: 2,
    Pie: 3
});
